#!/usr/bin/env python3
"""Generate the compact English -> Chinese lookup (Appendix E.3, 24f-english-index.tex).

The pinyin-ordered main glossary with definitions is E.1 (generate_bilingual_glossary.py).
This lookup repeats no definitions: English name, Chinese name and the same page targets.
Run after the glossary generator; it writes the file directly (no --check option).
"""
from __future__ import annotations

from pathlib import Path
import re

from generate_bilingual_glossary import glossary_rows

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "book" / "chapters" / "24e-bilingual-glossary.tex"
TARGET = ROOT / "book" / "chapters" / "24f-english-index.tex"
COLUMN = (r">{\raggedright\arraybackslash}p{37mm}>{\raggedright\arraybackslash}p{26.5mm}"
          r">{\raggedright\arraybackslash}p{13mm}")
HEADER = r"English & 中文 & 页码 & English & 中文 & 页码\\\midrule"


def main() -> None:
    source = SOURCE.read_text(encoding="utf-8")
    rows = glossary_rows()
    declared = re.search(r"全量中英对照：(\d+) 项", source)
    if not declared or int(declared[1]) != len(rows):
        raise SystemExit("Declared glossary count must match generated rows; run generate_bilingual_glossary.py first")
    grouped: dict[str, list[tuple[str, str]]] = {}
    for row in rows:
        letter = row["en"][0].upper()
        if not "A" <= letter <= "Z":
            raise SystemExit(f"Invalid English index key: {row['en']}")
        grouped.setdefault(letter, []).append(
            (row["en"].casefold(), row["en"] + " & " + row["zh"] + " & " + row["pages"]))
    text = [
        "% AUTO-GENERATED by scripts/generate_english_index.py. DO NOT EDIT.",
        r"\subsection{英文索引：从英文名称查到中文术语}",
        r"\phantomsection\label{app:english-index}",
        r"只列英文名、中文名与页码；释义与节号见\hyperref[app:bilingual-glossary]{按拼音排序的中英对照表（第~\pageref*{app:bilingual-glossary}~页）}。",
        r"\begingroup\footnotesize",
        r"\setlength{\tabcolsep}{3pt}",
        r"\renewcommand{\arraystretch}{1.0}",
        r"\tagpdfsetup{table/header-rows={1}}",
        # Two entries per row: a short lookup list should not spill onto an
        # almost empty page. Entries read left to right within each initial.
        r"\begin{longtable}{@{}" + (COLUMN * 2) + r"@{}}",
        r"\toprule",
        HEADER,
        r"\endfirsthead",
        r"\toprule",
        HEADER,
        r"\endhead",
        r"\bottomrule",
        r"\endfoot",
    ]
    for letter in sorted(grouped):
        # The initial opens its group's first row instead of using a row of its own.
        text.append(r"\addlinespace[2pt]")
        cells = [tex for _, tex in sorted(grouped[letter])]
        cells[0] = r"{\sffamily\bfseries\color{blue}" + letter + r"}\enspace " + cells[0]
        for i in range(0, len(cells), 2):
            pair = cells[i:i + 2] + ([" & & "] if i + 1 >= len(cells) else [])
            text.append(" & ".join(pair) + r"\\")
    text += [r"\end{longtable}", r"\endgroup", ""]
    TARGET.write_text("\n".join(text), encoding="utf-8")
    print(f"English index generated: {len(rows)} linked terms; {len(grouped)} initials")


if __name__ == "__main__":
    main()
