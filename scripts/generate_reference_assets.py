#!/usr/bin/env python3
"""Generate the printable reference QR and dated web index from the source audit."""
import argparse
import json
from pathlib import Path
from urllib.parse import urlsplit
import qrcode
ROOT=Path(__file__).resolve().parents[1]
URL='https://github.com/CoCoThink/ai-by-intuition/blob/main/docs/REFERENCES.md'
def outputs():
    rows=json.loads((ROOT/'book/source-audit.json').read_text())
    lines=['# 参考链接与核验记录','','纸质版附录 F 的二维码指向本页。核验日期采用 UTC；可访问表示入口检查，不表示全部内容均已复核。','','| 来源 | 核验日期（UTC） | 结果 |','| --- | --- | --- |']
    for r in rows:
        label=urlsplit(r['url']).netloc+urlsplit(r['url']).path
        result=r.get('result','访问受限' if r.get('status',200)>=400 else '链接可访问')
        lines.append(f"| [{label}]({r['url']}) | {r['checked_utc']} | {result} |")
    qr=qrcode.QRCode(error_correction=qrcode.constants.ERROR_CORRECT_M,border=4);qr.add_data(URL);qr.make(fit=True)
    matrix=qr.get_matrix();rects=[]
    for y,row in enumerate(matrix):
        x=0
        while x<len(row):
            if not row[x]:x+=1;continue
            end=x+1
            while end<len(row) and row[end]:end+=1
            rects.append(f'({x},{y}) rectangle ({end},{y+1})');x=end
    tex=[r'% Generated by scripts/generate_reference_assets.py.',r'\par\smallskip',r'\tagstructbegin{tag=Figure,alttext={二维码指向本书仓库的完整参考链接与核验记录。}}',r'\begin{center}',r'\begin{tikzpicture}[x=.48mm,y=-.48mm]',f'\\useasboundingbox (0,0) rectangle ({len(matrix)},{len(matrix)});',r'\fill[black]']
    tex+=rects;tex+=[';',r'\end{tikzpicture}\par',r'\tagstructbegin{tag=Caption}{\small 纸质版参考入口：扫码打开完整链接清单}\par\tagstructend',r'\end{center}',r'\tagstructend','']
    return {ROOT/'docs/REFERENCES.md':'\n'.join(lines)+'\n',ROOT/'book/figures/reference-qr.tex':'\n'.join(tex)}
def main():
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args()
    for path,content in outputs().items():
        if a.check:assert path.read_text()==content,f'Stale reference asset: {path}'
        else:path.write_text(content)
    print('Reference QR/index QA passed: fixed destination, audit dates and access exceptions')
if __name__=='__main__':main()
