#!/usr/bin/env python3
"""One chapter-ordered exercise bank and matching solutions from exercises.json.

The JSON is the only editable exercise source. Stable visible C-xxx IDs are
shared by chapter pointers, questions and answers; old IDs are hidden aliases.
"""
from __future__ import annotations
import argparse
from collections import defaultdict
import json
from pathlib import Path
import re
from generate_chapter_navigation import lesson_metadata

ROOT=Path(__file__).resolve().parents[1]
BOOK=ROOT/'book'


def load_exercises():
    data=json.loads((BOOK/'exercises.json').read_text())
    ids=[r['id'] for r in data]
    if len(set(ids))!=len(ids) or not all(re.fullmatch(r'C-\d{3}',i) for i in ids):
        raise ValueError('Exercise IDs must be unique C-xxx identifiers')
    owners,titles=lesson_metadata()
    primary={}
    for label,slug in owners.items():
        if label.startswith('intro:'):primary.setdefault(slug,label)
    for r in data:
        if r['slug'] in primary and r['owner']!=primary[r['slug']]:
            raise ValueError(f"{r['id']}: chapter metadata points to a subsection")
        expected=owners.get(r['owner'], 'optimizer-details' if r['owner']=='app:optimizer-details' else None)
        if expected!=r['slug']:raise ValueError(f"{r['id']}: wrong chapter ownership {r['owner']}")
        if r['difficulty'] not in ('基础','标准','挑战') or not 1<=r['minutes']<=60:
            raise ValueError(f"{r['id']}: invalid difficulty/time")
        if any(ord(c)<32 and c!='\n' for key in ('question','solution') for c in r[key]):
            raise ValueError(f"{r['id']}: unexpected control character in TeX")
        if not r['question'] or '第一步' not in r['solution']:
            raise ValueError(f"{r['id']}: question/first step/solution missing")
        if r.get('part_review') and (not r.get('review_prompt') or
                any(ord(c)<32 for c in r['review_prompt'])):
            raise ValueError(f"{r['id']}: printable cumulative review prompt missing")
    return data,owners,titles


def render():
    data,owners,titles=load_exercises()
    order={slug:i for i,slug in enumerate(titles)}
    data=sorted(data,key=lambda r:(order.get(r['slug'],999),r['id']))
    question=[r'% Generated by scripts/generate_exercise_bank.py; edit book/exercises.json.',
              r'\subsection{按章练习：一套题号，难度另作标签}',r'\label{app:exercise-bank}',
              '按正文顺序找本章题目；难度、预计耗时与对应章页标在每题前。先做章内自测，再按需要选练本章题库。',
              r'题目与答案共用 C-xxx 题号；答案在附录 D.1，第~\pageref*{app:answers}~页。']
    answer=[r'% Generated by scripts/generate_exercise_bank.py; edit book/exercises.json.',
            r'\subsection{按章练习参考答案}',r'\phantomsection\label{app:answers}',
            '先遮住解题过程，只读第一步；独立完成后再核对结果、单位与形状。']
    current=None
    for r in data:
        slug=r['slug']; identifier=r['id']
        if current!=slug:
            if current is not None: question.append(r'\end{enumerate}');answer.append(r'\end{enumerate}')
            if slug=='optimizer-details': title='附录 A：优化器';owner='app:optimizer-details'
            elif slug=='00-guide': title='序章';owner='check:00-guide'
            else:title=titles[slug];owner=r['owner']
            heading=(r'\subsubsection*{'+ (title if slug in ('optimizer-details','00-guide') else
                     r'第~\ref*{'+owner+r'}~章 · '+title) +'}')
            question += [heading,r'\begin{enumerate}[label={},leftmargin=4.8em,itemsep=4pt]']
            answer += [heading,r'\begin{enumerate}[label={},leftmargin=4.8em,itemsep=4pt]']
            current=slug
        alias=(r'\label{exercise:'+r['legacy_id']+'}' if r['legacy_id'] else '')
        owner=(r'附录 A（第~\pageref*{app:optimizer-details}~页）' if slug=='optimizer-details'
               else (r'序章／第~\pageref*{check:00-guide}~页' if slug=='00-guide' else r'第~\ref*{'+r['owner']+r'}~章／第~\pageref*{'+r['owner']+'}~页'))
        question += [r'\item[\textbf{'+identifier+r'.}] \phantomsection\label{exercise:'+identifier+'}'+alias+
                     r'\exercisemeta{'+r['difficulty']+'}{'+str(r['minutes'])+'}{'+owner+'}'+r['question']+
                     r' \hyperref[solution:'+identifier+r']{解答见第~\pageref*{solution:'+identifier+r'}~页。}']
        legacy=(r'\phantomsection\label{'+r['legacy_answer_anchor']+'}' if r['legacy_answer_anchor'] else '')
        answer += [r'\item[\textbf{'+identifier+r'.}] \phantomsection\label{solution:'+identifier+'}'+legacy+
                   r'\hyperref[exercise:'+identifier+r']{题目见第~\pageref*{exercise:'+identifier+r'}~页。}\par\nobreak '+r['solution']]
    question.append(r'\end{enumerate}');answer.append(r'\end{enumerate}')
    reviews=[r'% Generated by scripts/generate_exercise_bank.py; edit book/exercises.json.']
    for part in ('learning','matrices','tokens','context','transformer','vision','assistant','architecture','memory'):
        selected=[r for r in data if r.get('part_review')==part]
        if len(selected)!=2: raise ValueError(f'{part}: expected two cumulative reviews')
        reviews += [r'\newcommand{\partreview'+part+r'}{\par\Needspace{4\baselineskip}\begingroup\small\setlength{\parskip}{2pt}',
                    r'\noindent{\sffamily\bfseries 本部分累积复习}\par',
                    r'\begin{enumerate}[label={},leftmargin=4.8em,itemsep=2pt,topsep=2pt,parsep=0pt]']
        for r in selected:
            reviews += [r'\item[\textbf{'+r['id']+r'.}] '+r['review_prompt']+
                        r' \hyperref[solution:'+r['id']+r']{提示与解答见第~\pageref*{solution:'+r['id']+r'}~页。}']
        reviews += [r'\end{enumerate}\endgroup}']
    return {BOOK/'part-reviews.tex':'\n'.join(reviews)+'\n',BOOK/'chapters/25-exercise-bank.tex' :'\n'.join(question)+'\n',
            BOOK/'chapters/27-answer-key.tex':'\n'.join(answer)+'\n'}


def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');args=p.parse_args()
    for path,text in render().items():
        if args.check:
            if not path.exists() or path.read_text()!=text:raise SystemExit(f'Stale exercise output: {path}')
        else:path.write_text(text)
    data,_,_=load_exercises()
    print(f'Exercise bank QA: {len(data)} uniquely numbered questions and matching first-step solutions in chapter order')


if __name__=='__main__':main()
