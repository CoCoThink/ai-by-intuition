#!/usr/bin/env python3
"""Generate a 136-entry Chinese-first pinyin index from the bilingual glossary."""
from __future__ import annotations

from collections import defaultdict
from pathlib import Path
import re

from pypinyin import lazy_pinyin

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "book" / "chapters" / "24e-bilingual-glossary.tex"
TARGET = ROOT / "book" / "chapters" / "24f-chinese-index.tex"

ROW = re.compile(
    r"^(.+?) & (.+?) & (.+?) & \\hyperref\[([^]]+)\]",
    re.MULTILINE
)
CJK = re.compile(r"[\u3400-\u9fff]")


def sort_key(chinese: str) -> str:
    match = CJK.search(chinese)
    # Terms can begin with Latin abbreviations (e.g. Adam Optimizer).
    subject = chinese[match.start():] if match else chinese
    return " ".join(lazy_pinyin(subject)).casefold()


def main() -> None:
    source = SOURCE.read_text(encoding="utf-8")
    rows = ROW.findall(source)
    if len(rows) != 136:
        raise SystemExit(f"Expected 136 glossary terms, got {len(rows)}")
    grouped = defaultdict(list)
    for zh, en, _definition, target in rows:
        key = sort_key(zh)
        letter = key[0].upper()
        if letter < "A" or letter > "Z":
            raise SystemExit(f"Invalid pinyin index key: {zh}: {key}")
        grouped[letter].append((key, zh, en, target))
    text = [
        "% AUTO-GENERATED by scripts/generate_chinese_index.py. DO NOT EDIT.",
        r"\subsection{中文拼音索引：从中文术语返回正文}",
        r"\phantomsection\label{app:chinese-index}",
        "按中文名称的普通话拼音顺序排列，优先从第一个汉字检索；",
        "缩写词与英文起首的术语按照名称中的首个汉字归类。",
        "每一项的页码是可点击的正文位置；英文全量定义见上一张对照表。",
        r"\begingroup\footnotesize",
        r"\setlength{\tabcolsep}{3pt}",
        r"\renewcommand{\arraystretch}{1.10}",
        r"\tagpdfsetup{table/header-rows={1}}",
        r"\begin{longtable}{@{}>{\raggedright\arraybackslash}p{47mm}>{\raggedright\arraybackslash}p{80mm}>{\centering\arraybackslash}p{20mm}@{}}",
        r"\toprule",
        r"中文术语 & English & 章／页\\\midrule",
        r"\endfirsthead",
        r"\toprule",
        r"中文术语 & English & 章／页\\\midrule",
        r"\endhead",
        r"\bottomrule",
        r"\endfoot",
    ]
    for letter in sorted(grouped):
        text += [
            r"\addlinespace[3pt]",
            (r"\multicolumn{3}{@{}l}{\sffamily\bfseries "
             r"\color{blue}拼音 " + letter + r"}\\*"),
        ]
        for _, zh, en, dest in sorted(grouped[letter]):
            text.append(
                zh + " & " + en + " & "
                + r"\hyperref[" + dest + r"]{\ref*{" + dest
                + r"}/\pageref*{" + dest + r"}}\\"
            )
    text += [r"\end{longtable}", r"\endgroup", ""]
    TARGET.write_text("\n".join(text), encoding="utf-8")
    print(f"Pinyin index generated: {len(rows)} linked Chinese terms; {len(grouped)} initials")


if __name__ == "__main__":
    main()
