ENTRY = re.compile(
    r"(?m)^\\item\s+\\textbf\{([^}]+)\}：(.*?)\s+\\termref\{([^}]+)\}\s*$"
)
ALIAS = re.compile(
    r"(?m)^\\item \{\\sffamily\\bfseries ([^}]+)\} \\quad ([^\n]+?)\\quad \\termref\{([^}]+)\}"
)

def entries(file: str) -> list[tuple[str, str, str]]:
    text = (CHAPTERS / file).read_text(encoding="utf-8")
    return [(m.group(1), m.group(2).strip(), m.group(3))
            for m in ENTRY.finditer(text)]

def glossary_rows() -> list[dict[str, str]]:
    """Canonical rows: Chinese display name, English, definition and lookup cells."""
    base = entries("24-lexicon.tex")
    modern = entries("24b-modern-lexicon.tex")
    if len(base) != 100 or not modern:
        raise ValueError("Canonical inventory requires foundation entries and modern definitions")
    idx = (CHAPTERS / "24d-english-index.tex").read_text(encoding="utf-8")
    aliases = {m.group(2).strip(): m.group(1) for m in ALIAS.finditer(idx)}
    display = dict(line.split("=", 1) for line in OVERRIDES)
    modern_pairs = [line.split(" | ", 1) for line in MODERN_PAIRS]
    if len(modern_pairs) != len(modern):
        raise ValueError("Every modern definition requires an English mapping")
    if any(name not in aliases for name, _, _ in base):
        raise ValueError("English alias missing for a base definition")
    unknown = set(EXTRA_REFERENCES) - {name for name, _, _ in base + modern}
    if unknown:
        raise ValueError(f"Extra references for unknown terms: {sorted(unknown)}")
    rows = []
    for name, definition, reference in base:
        rows.append(dict(zh=display.get(name, name), en=aliases[name], definition=definition,
                         refs=reference_cell(name, reference), pages=reference_cell(name, reference, True)))
    for (name, definition, reference), (zh, en) in zip(modern, modern_pairs):
        rows.append(dict(zh=zh, en=en, definition=definition,
                         refs=reference_cell(name, reference), pages=reference_cell(name, reference, True)))
    return rows


def generate() -> str:
    rows = glossary_rows()
    lines = HEADER.replace('{row_count}', str(len(rows))).splitlines()
    groups: dict[str, list[tuple[tuple, str]]] = {}
    for row in rows:
        key = pinyin_key(row["zh"])
        letter = "字母开头" if not CJK.match(row["zh"][0]) else key[0][1][0].upper()
        if letter != "字母开头" and not "A" <= letter <= "Z":
            raise ValueError(f"Invalid pinyin index key: {row['zh']}")
        tex = f"{row['zh']} & {row['en']} & {row['definition']} & {row['refs']}" + r"\\"
        groups.setdefault(letter, []).append((key, tex))
    for letter in sorted(groups, key=lambda g: (g != "字母开头", g)):
        title = "以字母开头的中文名称" if letter == "字母开头" else "拼音 " + letter
        lines.append(r"\addlinespace[4pt]")
        lines.append(r"\multicolumn{4}{@{}l}{\sffamily\bfseries\color{blue} " + title + r"}\\*")
        lines.extend(tex for _, tex in sorted(groups[letter]))
    five_pairs = (CHAPTERS / "24-lexicon.tex").read_text(encoding="utf-8").split(
        r"\subsubsection*{不要混淆的五对概念}", 1
    )[1].strip()
    lines.extend([r"\end{longtable}", r"\endgroup", "",
                  r"\subsubsection*{不要混淆的五对概念}",
                  five_pairs, ""])
    return "\n".join(lines)

def occurrence_index(glossary: str) -> str:
    """List every matching core chapter, preserving first source location per chapter.

    The printed indices retain the definition and important worked examples;
    common terms such as 'model' would otherwise fill pages with references.
    """
    from check_chapter_crossrefs import uncomment
    from generate_chapter_navigation import argument
    main = uncomment((ROOT / 'book/main.tex').read_text()).split(r'\appendix', 1)[0]
    rows = [(r['en'], r['zh'], r['definition'], r['refs']) for r in glossary_rows()]
    chapters = []
    number = 0
    for name in re.findall(r'\\input\{chapters/([^}]+)\}', main):
        if name in ('00-guide', '23f-foundation-recap'):
            continue
        raw = (CHAPTERS / (name + '.tex')).read_text()
        body = uncomment(raw)
        for hidden in ('chapterinlinehint', 'modelpipelinefocus'):
            while (match := re.search(r'\\' + hidden + r'\{', body)):
                _, end = argument(body, match.end()-1)
                if hidden == 'modelpipelinefocus':
                    _, end = argument(body, end)
                body = body[:match.start()] + '\n' * body[match.start():end].count('\n') + body[end:]
        starts = list(re.finditer(r'\\section\{', body))
        if not starts:
            if chapters:
                chapters[-1]['sources'].append((name, body))
            continue
        if starts[0].start() and chapters:
            chapters[-1]['sources'].append((name, body[:starts[0].start()]))
        for i, match in enumerate(starts):
            number += 1
            title, _ = argument(body, match.end()-1)
            segment = body[match.start():starts[i+1].start() if i+1 < len(starts) else len(body)]
            chapters.append(dict(number=number, title=title, sources=[(name, segment)]))
    output = ['# 术语正文出现章节', '',
        '此表由正文自动生成；列出每个词出现的全部章节，每章链接到首次命中的源码文件。'
        '纸质版索引保留定义与主要算例的自动页码；本表补充经过提及的位置。'
        '匹配中文名称及英文全称，忽略隐藏提示；不统计练习答案和附录。', '',
        '| 中文／English | 正文出现章节 |', '| --- | --- |']
    for en, zh, _definition, _references in sorted(rows, key=lambda row: row[0].casefold()):
        terms = [en, zh, *re.findall(r'\(([A-Za-z][A-Za-z0-9/-]*)\)', en)]
        if en == 'BOS/EOS': terms += ['BOS', 'EOS']
        matches = []
        for chapter in chapters:
            for name, body in chapter['sources']:
                found = any(r'\label{'+target+'}' in body for target in re.findall(r'\\hyperref\[([^]]+)\]', _references))
                if found:
                    matches.append(f"[第 {chapter['number']} 章](../book/chapters/{name}.tex)");break
                for term in terms:
                    if re.search(r'[\u3400-\u9fff]', term):
                        found = term in body
                    else:
                        found = bool(re.search(r'(?<![A-Za-z])' + re.escape(term) + r'(?![A-Za-z])', body, re.I))
                    if found:
                        matches.append(f"[第 {chapter['number']} 章](../book/chapters/{name}.tex)")
                        break
                if found:
                    break
        output.append(f"| {zh} / {en} | " + ('、'.join(matches) or '见纸质版定义入口') + ' |')
    return '\n'.join(output) + '\n'


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = generate()
    occurrences = occurrence_index(output)
    occurrence_target = ROOT / 'docs/TERM_OCCURRENCES.md'
    if args.check:
        if (not TARGET.is_file() or TARGET.read_text(encoding="utf-8") != output
                or not occurrence_target.is_file() or occurrence_target.read_text() != occurrences):
            print("Bilingual glossary is stale. Regenerate its TeX.", file=sys.stderr)
            return 1
        print(f"{len(entries('24-lexicon.tex')) + len(entries('24b-modern-lexicon.tex'))}-row bilingual glossary QA passed")
        return 0
    TARGET.write_text(output, encoding="utf-8")
    occurrence_target.write_text(occurrences, encoding='utf-8')
    print("Updated bilingual glossary from canonical definitions.")
    return 0

if __name__ == "__main__":
    sys.exit(main())
