def reference_cell(term: str, reference: str, short: bool = False) -> str:
    """Section/page in the main table; page only in the English lookup."""
    sep = "、" if short else r"\newline "
    text = (r"\pageref*{%s}" if short else r"\ref*{%s}/\pageref*{%s}")
    return sep.join(
        r"\hyperref[" + target + "]{" + (text % target if short else text % (target, target)) + "}"
        for target in (reference, *EXTRA_REFERENCES.get(term, ()))
    )


def pinyin_key(chinese: str) -> tuple:
    """Character-by-character pinyin (with tone), so terms sharing a first
    character stay together: 预填充, 预训练 precede 余弦 only by tone order."""
    from pypinyin import Style, lazy_pinyin
    key = []
    for ch in chinese:
        if CJK.match(ch):
            key.append((1, lazy_pinyin(ch, style=Style.TONE3, neutral_tone_with_five=True)[0], ch))
        elif ch.isspace():
            key.append((-1, "", ""))  # word end sorts first: Adam before AdamW
        else:
            key.append((0, ch.casefold(), ch))
    return tuple(key)

