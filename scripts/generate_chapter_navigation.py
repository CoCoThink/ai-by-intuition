#!/usr/bin/env python3
"""Derive chapter practice links from Appendix C ownership; guard answer titles.

Run after changing exercises: python3 scripts/generate_chapter_navigation.py
CI uses --check to reject stale generated links or mismatched answer headings.
"""
from __future__ import annotations
import argparse
from collections import defaultdict
from pathlib import Path
import re
from check_chapter_crossrefs import uncomment

ROOT = Path(__file__).resolve().parents[1]
BOOK = ROOT / 'book'
OUTPUT = BOOK / 'chapter-practice.tex'
COLLECTIONS = (('25-integrated-practice', 'C1'), ('25b-modern-practice', 'C2'),
               ('15-practice', 'C3'), ('25c-migrated-review', 'C4'))


def argument(text: str, start: int) -> tuple[str, int]:
    """Read a balanced TeX argument, preserving any nested commands."""
    assert text[start] == '{'
    depth = 1
    for i in range(start + 1, len(text)):
        if text[i] in '{}' and text[i-1] != '\\':
            depth += 1 if text[i] == '{' else -1
            if not depth:
                return text[start+1:i], i+1
    raise ValueError('Unclosed TeX argument')


def lesson_metadata() -> tuple[dict[str, str], dict[str, str]]:
    """Follow compilation order, including chapters split across source files."""
    main = uncomment((BOOK / 'main.tex').read_text())
    owners, titles = {}, {}
    section, checks, section_labels = '', [], []
    def flush():
        if checks:
            for slug in checks:
                titles[slug] = section
            for label in section_labels:
                owners[label] = checks[0]
    for name in re.findall(r'\\input\{chapters/([^}]+)\}', main):
        body = uncomment((BOOK / 'chapters' / (name + '.tex')).read_text())
        for event in re.finditer(r'\\section\*?\s*\{|\\label\{intro:([^}]+)\}|'
                                 r'\\chapterchecktasks\{([^}]+)\}', body):
            if event[0].startswith('\\section'):
                flush()
                section, _ = argument(body, event.end()-1)
                checks, section_labels = [], []
            elif event[1]:
                section_labels.append('intro:' + event[1])
            else:
                checks.append(event[2])
    flush()
    return owners, titles


def rendered_navigation() -> str:
    owners, titles = lesson_metadata()
    links = defaultdict(list)
    count = 0
    for name, prefix in COLLECTIONS:
        source = uncomment((BOOK / 'chapters' / (name + '.tex')).read_text())
        for number, match in enumerate(re.finditer(r'\\item\b(?:\[[^]]*\])?(.*?)(?=\\item\b|\\end\{enumerate\})',
                                                  source, re.S), 1):
            body = match[1]
            identifier = f'{prefix}-{number}'
            if r'\label{exercise:' + identifier + '}' not in body:
                raise ValueError(f'{name}: missing stable exercise label {identifier}')
            metadata = re.search(r'\\exercisemeta\{', body)
            if not metadata or body.count(r'\exercisemeta{') != 1:
                raise ValueError(f'{identifier}: needs difficulty, time and chapter metadata')
            difficulty, end = argument(body, metadata.end()-1)
            minutes, end = argument(body, end)
            chapter, _ = argument(body, end)
            if difficulty not in ('基础', '标准', '挑战'):
                raise ValueError(f'{identifier}: unknown difficulty {difficulty}')
            if not minutes.isdigit() or not 1 <= int(minutes) <= 60:
                raise ValueError(f'{identifier}: invalid suggested time {minutes}')
            if r'\ref*{' not in chapter and r'\hyperref[' not in chapter:
                raise ValueError(f'{identifier}: chapter metadata must link to its source')
            label = re.search(r'\\ref\*\{(intro:[^}]+)\}', body)
            extension = re.search(r'\\label\{extension:([^:}]+):(\d+)\}', body)
            if extension:
                slug = extension[1]
                if slug not in titles:
                    raise ValueError(f'{identifier}: unknown chapter self-check {slug}')
            elif label:
                if label[1] not in owners:
                    raise ValueError(f'{identifier}: no chapter self-check for {label[1]}')
                slug = owners[label[1]]
            else:
                # The two optimizer exercises belong to Appendix A, not a core chapter.
                if r'\hyperref[app:optimizer-details]' not in body:
                    raise ValueError(f'{identifier}: missing chapter/appendix ownership')
                slug = 'optimizer-details'
            links[slug].append(r'\hyperref[exercise:' + identifier + ']{' + identifier + '}')
            count += 1
    if count != 101:
        raise ValueError(f'Expected 101 numbered practice exercises, got {count}')
    lines = ['% Generated by scripts/generate_chapter_navigation.py; edit exercise ownership in Appendix C.']
    for slug in sorted(links):
        lines.append(r'\expandafter\gdef\csname chapterpractice@' + slug +
                     r'\endcsname{' + '、'.join(links[slug]) + '}')
    return '\n'.join(lines) + '\n'


def validate_navigation() -> list[str]:
    errors = []
    expected = rendered_navigation()
    if not OUTPUT.is_file() or OUTPUT.read_text() != expected:
        errors.append('Chapter practice navigation is stale; run scripts/generate_chapter_navigation.py')
    _, titles = lesson_metadata()
    answers = (BOOK / 'chapters/28-chapter-checks.tex').read_text()
    seen = set()
    for match in re.finditer(r'\\label\{answer:([^}]+)\}\\textbf\{\\hyperref\[check:([^]]+)\]\{', answers):
        slug = match[1]
        title, _ = argument(answers, match.end()-1)
        if slug != match[2] or title != titles.get(slug):
            errors.append(f'Answer heading {slug} must match chapter title: {titles.get(slug)}')
        seen.add(slug)
    # A hint is a separate argument, so removing one cannot silently turn a
    # solution's first character into the hint when TeX expands the macro.
    for match in re.finditer(r'\\answerpiece\{([^}]+)\}\{', answers):
        _, end = argument(answers, match.end()-1)
        if end >= len(answers) or answers[end] != '{':
            errors.append(f'Missing first step at answer item {match[1]}')
            continue
        hint, _ = argument(answers, end)
        if len(hint.strip()) < 6:
            errors.append(f'First step too short at answer item {match[1]}')
    if seen != set(titles):
        errors.append(f'Answer heading coverage mismatch: {seen ^ set(titles)}')
    extensions = (BOOK / 'chapters/25c-migrated-review.tex').read_text()
    for match in re.finditer(r'\\subsubsection\*\{\\hyperref\[check:([^]]+)\]\{', extensions):
        title, _ = argument(extensions, match.end()-1)
        if title != titles.get(match[1], '') + '（返回正文）':
            errors.append(f'Extension heading {match[1]} must match its chapter')
    for number, match in enumerate(re.finditer(
            r'\\label\{exercise:(C4-\d+)\}\\label\{extension:([^:}]+):(\d+)\}', extensions), 1):
        identifier, slug, legacy = match.groups()
        if identifier != f'C4-{number}':
            errors.append(f'Appendix C4 is out of order: {identifier}')
        expected = (r'\label{answerpiece:' + slug + ':' + legacy +
                    r'}\answerpiece{' + identifier + '}')
        if expected not in answers:
            errors.append(f'{identifier} must use the same visible ID in Appendix D')
    return errors


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    if not args.check:
        OUTPUT.write_text(rendered_navigation())
    errors = validate_navigation()
    if errors:
        for error in errors:
            print('NAVIGATION QA FAILED:', error)
        return 1
    print('Navigation QA passed: 101 numbered exercises mapped; all 45 answer titles match their chapters')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
