#!/usr/bin/env python3
"""Derive practice links and the contributor source map; guard answer titles.

Run after changing exercises, chapter inputs, labels or filenames:
python3 scripts/generate_chapter_navigation.py
CI uses --check to reject stale navigation/source maps or mismatched answer headings.
"""
from __future__ import annotations
import argparse
from collections import defaultdict
from pathlib import Path
import re
from check_chapter_crossrefs import uncomment

ROOT = Path(__file__).resolve().parents[1]
BOOK = ROOT / 'book'
OUTPUT = BOOK / 'chapter-practice.tex'
GUIDE = ROOT / 'CONTRIBUTING.md'
MAP_BEGIN = '<!-- BEGIN GENERATED CHAPTER SOURCE MAP -->'
MAP_END = '<!-- END GENERATED CHAPTER SOURCE MAP -->'

def argument(text: str, start: int) -> tuple[str, int]:
    """Read a balanced TeX argument, preserving any nested commands."""
    assert text[start] == '{'
    depth = 1
    for i in range(start + 1, len(text)):
        if text[i] in '{}' and text[i-1] != '\\':
            depth += 1 if text[i] == '{' else -1
            if not depth:
                return text[start+1:i], i+1
    raise ValueError('Unclosed TeX argument')


def lesson_metadata() -> tuple[dict[str, str], dict[str, str]]:
    """Follow compilation order; stable label/check IDs do not depend on filenames."""
    main = uncomment((BOOK / 'main.tex').read_text())
    owners, titles = {}, {}
    section, checks, section_labels = '', [], []
    def flush():
        if checks:
            for slug in checks:
                titles[slug] = section
                owners['check:' + slug] = slug
            for label in section_labels:
                owners[label] = checks[0]
    for name in re.findall(r'\\input\{chapters/([^}]+)\}', main.split(r'\appendix', 1)[0]):
        body = uncomment((BOOK / 'chapters' / (name + '.tex')).read_text())
        for event in re.finditer(r'\\section\*?\s*\{|\\label\{intro:([^}]+)\}|'
                                 r'\\chapterchecktasks\{([^}]+)\}', body):
            if event[0].startswith('\\section'):
                flush()
                section, _ = argument(body, event.end()-1)
                checks, section_labels = [], []
            elif event[1]:
                section_labels.append('intro:' + event[1])
            else:
                checks.append(event[2])
    flush()
    return owners, titles


def practice_links(identifiers):
    """Show consecutive IDs as ranges; endpoints keep their own destinations."""
    def link(identifier):
        return r'\hyperref[exercise:' + identifier + ']{' + identifier + '}'
    groups=[]
    for identifier in sorted(identifiers):
        if groups and int(identifier[2:]) == int(groups[-1][-1][2:])+1:
            groups[-1].append(identifier)
        else:
            groups.append([identifier])
    return '、'.join(link(group[0]) + ('--'+link(group[-1]) if len(group)>1 else '')
                    for group in groups)


def rendered_navigation() -> str:
    from generate_exercise_bank import load_exercises
    data, _, _ = load_exercises()
    links = defaultdict(list)
    for item in data:
        if item.get('part_review'):continue
        links[item['slug']].append(item['id'])
    lines = ['% Generated by scripts/generate_chapter_navigation.py; edit book/exercises.json.']
    for slug in sorted(links):
        lines.append(r'\expandafter\gdef\csname chapterpractice@' + slug +
                     r'\endcsname{' + practice_links(links[slug]) + '}')
    return '\n'.join(lines) + '\n'


def rendered_source_map() -> str:
    """Map stable entry labels and practice slugs to actual compilation inputs."""
    main = uncomment((BOOK / 'main.tex').read_text())
    lines = ['| 当前章文件 | 入口与兼容标签 | 习题归属键（`slug`） |',
             '|---|---|---|']
    for name in re.findall(r'\\input\{chapters/([^}]+)\}', main):
        body = uncomment((BOOK / 'chapters' / (name + '.tex')).read_text())
        slugs = re.findall(r'\\(?:chapterchecktasks|chapterpracticejump)\{([^}]+)\}', body)
        if not slugs:
            continue
        labels = re.findall(r'\\label\{(intro:[^}]+|front:prologue|app:optimizer-details)\}', body)
        label_cell = '<br>'.join(f'`{label}`' for label in labels)
        slug_cell = '<br>'.join(f'`{slug}`' for slug in dict.fromkeys(slugs))
        lines.append(f'| [{name}.tex](book/chapters/{name}.tex) | {label_cell} | {slug_cell} |')
    return '\n'.join(lines)


def updated_source_guide() -> str:
    guide = GUIDE.read_text()
    start = guide.index(MAP_BEGIN) + len(MAP_BEGIN)
    end = guide.index(MAP_END, start)
    return guide[:start] + '\n' + rendered_source_map() + '\n' + guide[end:]


def validate_navigation() -> list[str]:
    errors = []
    if not OUTPUT.is_file() or OUTPUT.read_text() != rendered_navigation():
        errors.append('Chapter practice navigation is stale; run scripts/generate_chapter_navigation.py')
    if GUIDE.read_text() != updated_source_guide():
        errors.append('Contributor label/source map is stale; run scripts/generate_chapter_navigation.py')
    _, titles = lesson_metadata()
    answers = (BOOK / 'chapters/appendix-d-self-check-solutions.tex').read_text()
    seen = set()
    for match in re.finditer(r'\\label\{answer:([^}]+)\}\\textbf\{\\hyperref\[check:([^]]+)\]\{', answers):
        slug = match[1]
        title, _ = argument(answers, match.end()-1)
        if slug != match[2] or title != titles.get(slug):
            errors.append(f'Answer heading {slug} must match chapter title: {titles.get(slug)}')
        if slug in seen: errors.append(f'Duplicate answer heading: {slug}')
        seen.add(slug)
    for match in re.finditer(r'\\answerpiece\{([^}]+)\}\{', answers):
        _, end = argument(answers, match.end()-1)
        if end >= len(answers) or answers[end] != '{':
            errors.append(f'Missing first step at answer item {match[1]}')
            continue
        hint, _ = argument(answers, end)
        if len(hint.strip()) < 6: errors.append(f'First step too short: {match[1]}')
    if seen != set(titles): errors.append(f'Answer heading coverage mismatch: {seen ^ set(titles)}')
    return errors


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    if not args.check:
        OUTPUT.write_text(rendered_navigation())
        GUIDE.write_text(updated_source_guide())
    errors = validate_navigation()
    if errors:
        for error in errors:
            print('NAVIGATION QA FAILED:', error)
        return 1
    print('Navigation QA passed: practice/source maps current; all answer titles match their chapters')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
